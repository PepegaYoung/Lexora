        layout.addWidget(self.filter_description)
        def describe():
            profile = next(p for p in ocr.PROFILES if p[0]==self.filter_pick.currentData())
            self.filter_description.setToolTip(profile[2])
        self.filter_pick.currentIndexChanged.connect(describe)
        describe()
        layout.addWidget(button('Проверить профиль на выбранной области',self.preview_ocr))
        layout.addWidget(note('Предпросмотр покажет исходный кадр, обработку и распознанный текст. Если области нет, сначала выбери её на вкладке «В игре».'))
        layout.addWidget(button('Применить профиль',self.apply_settings,True))
        self.hotkey_fields = {}
        shortcuts = section(layout,'Горячие клавиши')
        form = QFormLayout()
        for action,label in [('study','Разбор кадра'),('region','Выбор области'),('toggle','Автоперевод / пауза'),('screen','Перевести текущий кадр'),('hover','Наведение')]:
            field = HotkeyEdit(self.settings['hotkeys'][action])
            field.recordingChanged.connect(self.recording_changed)
            field.recorded.connect(lambda chord,key=action:self.record_hotkey(key,chord))
            field.invalid.connect(self.message)
            self.hotkey_fields[action] = field
            row=QWidget()
            buttons=QHBoxLayout(row);buttons.setContentsMargins(0,0,0,0)
            buttons.addWidget(field,1)
            add,remove=QPushButton('+'),QPushButton('−')
            for control in (add,remove):control.setFixedWidth(36)
            add.setToolTip('Добавить ещё одну клавишу или сочетание для этой команды.')
            remove.setToolTip('Удалить одну из привязок этой команды.')
            add.setAccessibleName('Добавить привязку: '+label)
            remove.setAccessibleName('Удалить привязку: '+label)
            add.clicked.connect(field.begin_add)
            remove.clicked.connect(lambda checked=False,key=action:self.remove_hotkey(key))
            buttons.addWidget(add);buttons.addWidget(remove)
            form.addRow(label,row)
        shortcuts.addLayout(form)
        shortcuts.addWidget(note('Нажми поле → прожми клавишу или сочетание. «+» добавляет вариант, «−» удаляет. Сохраняется сразу; Escape отменяет запись.'))
        shortcuts.addWidget(note('До четырёх привязок на команду. Одиночные клавиши освобождаются в обычных окнах Lexora для ввода текста; на снимке кадра они работают.'))
        layout.addStretch()
        self.tabs.addTab(scroll(page),'Распознавание')

